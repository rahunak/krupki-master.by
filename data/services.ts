export interface PriceItem {
  name: string;
  /** Единица: «за точку», «за м²», «за выезд» */
  unit: string;
  /** Цена «от» в BYN. null — прайс не согласован владельцем */
  priceFrom: number | null;
  note?: string;
}

export interface FaqItem {
  q: string;
  a: string;
}

export interface Service {
  slug: ServiceSlug;
  /** path раздела: /uslugi/<slug>/ */
  path: string;
  /** title по шаблону SDD 3.2 (до 60 символов до разделителя) */
  title: string;
  description: string;
  h1: string;
  /** Название для микроразметки Service */
  serviceName: string;
  /** Вводный абзац под H1 */
  lead: string;
  /** Иллюстративное фото услуги (не пример выполненного объекта).
   *  Необязательно: для услуги без подходящей честной иллюстрации
   *  страница рендерится без фото, а не со стоковой заглушкой не по теме. */
  image?: string;
  imageAlt?: string;
  /** Что делаем — перечень работ */
  whatWeDo: string[];
  /** Как проходит работа — этапы */
  steps: { title: string; text: string }[];
  prices: PriceItem[];
  faq: FaqItem[];
  /** 1 — приоритет 6 месяцев, 2 — второй приоритет (SDD 9.3, 9.9) */
  priority: 1 | 2;
  /** Кому подходит / когда вызывать */
  reasons: string[];
}

